"""Generate server/src/game_catalog.h from the game's data tables.

Export the tables with UAssetGUI (UE 4.15, unversioned cook) first:
    UAssetGUI.exe tojson MissionData.uasset MissionData.json VER_UE4_15
    UAssetGUI.exe tojson BadgeData.uasset BadgeData.json VER_UE4_15
    UAssetGUI.exe tojson WappenData.uasset WappenData.json VER_UE4_15
from TG4AC/Content/DataTables/GameData, .../Badge and .../Wappen, then run
    python extract_catalog.py <export dir> <output header>
Only ids are written: names, textures and texts stay in the game's own data.
"""
import json
import sys
from pathlib import Path


def table_rows(path: Path) -> list:
    data = json.loads(path.read_text(encoding="utf-8"))
    tables = [e for e in data["Exports"] if "DataTable" in e["$type"]]
    if len(tables) != 1:
        raise SystemExit("%s: expected one DataTable export, found %d" % (path, len(tables)))
    return tables[0]["Table"]["Data"]


def field(row: dict, name: str) -> object:
    for prop in row["Value"]:
        if prop["Name"] == name:
            return prop.get("Value")
    raise SystemExit("row %s has no field %s" % (row["Name"], name))


def train_line(number: int) -> int:
    # The mission command asks for train_line 1..8. MissionNumber / 10000 is
    # that line. The two numbers below 10000 belong to line 1.
    prefix = number // 10000
    if prefix == 0:
        return 1
    if prefix < 1 or prefix > 8:
        raise SystemExit("mission %s is outside train_line 1..8" % number)
    return prefix


def int_array(name: str, values: list, per_line: int = 12) -> str:
    lines = []
    for start in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(v) for v in values[start:start + per_line]) + ",")
    return "constexpr int %s[] = {\n%s\n};\n" % (name, "\n".join(lines))


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit("usage: extract_catalog.py <export dir> <output header>")
    exports = Path(sys.argv[1])
    output = Path(sys.argv[2])

    mission_rows = table_rows(exports / "MissionData.json")
    missions = sorted(field(row, "MissionNumber") for row in mission_rows)
    debug = sorted(
        field(row, "MissionNumber")
        for row in mission_rows
        if field(row, "MissionCategory") == "EMissionCategory::Debug")
    lines = [train_line(number) for number in missions]
    badges = sorted(field(row, "BadgeId") for row in table_rows(exports / "BadgeData.json"))
    wappen = sorted(field(row, "WappenId") for row in table_rows(exports / "WappenData.json"))

    header = (
        "#pragma once\n\n"
        "// Generated by server/tools/extract_catalog.py from the game's DataTables\n"
        "// (GameData/MissionData, including Debug, Badge/BadgeData,\n"
        "// Wappen/WappenData). Do not edit by hand.\n\n"
        + int_array("kGameMissionNumbers", missions) + "\n"
        + "// Debug rows of MissionData. The normal-mode table is only the\n"
        + "// isNormalMode rows until version.dll appends these.\n"
        + int_array("kDebugMissionNumbers", debug) + "\n"
        + "// train_line on the mission command. MissionNumber / 10000, with the two\n"
        + "// numbers below 10000 kept on line 1. Parallel to kGameMissionNumbers.\n"
        + int_array("kGameMissionTrainLine", lines) + "\n"
        + "static_assert(\n"
        + "    sizeof(kGameMissionTrainLine) == sizeof(kGameMissionNumbers),\n"
        + "    \"one train line per mission\");\n\n"
        + int_array("kGameBadgeIds", badges) + "\n"
        + int_array("kGameWappenIds", wappen)
    )
    output.write_text(header, encoding="utf-8", newline="\n")
    print("%s: %d missions (%d debug), %d badges, %d wappen" % (
        output, len(missions), len(debug), len(badges), len(wappen)))


if __name__ == "__main__":
    main()
